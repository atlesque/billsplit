export const DICTIONARIES = { en, nl };

/** The first supported language in a list of BCP 47 tags such as navigator.languages. */
export function matchLanguage(tags) {
  for (const tag of tags ?? []) {
    const base = String(tag).toLowerCase().split("-")[0];
    if (base in LANGUAGES) return base;
  }
  return null;
}

function storedLanguage() {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    return value in LANGUAGES ? value : null;
  } catch {
    return null;
  }
}

/** The switcher's saved choice, else the browser language, else English. */
export function detectLanguage() {
  if (typeof navigator === "undefined") return "en";
  return storedLanguage() ?? matchLanguage(navigator.languages?.length ? navigator.languages : [navigator.language]) ?? "en";
}

let current = detectLanguage();
export const getLanguage = () => current;

export function setLanguage(lang) {
  if (!(lang in LANGUAGES)) return;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {}
  if (typeof document !== "undefined") document.documentElement.lang = lang;
}

/** Locale for dates and numbers: Dutch formatting for Dutch, the browser's own English variant for English. */
export function getLocale() {
  if (current === "nl") return "nl-NL";
  const browser = typeof navigator === "undefined" ? "" : navigator.language ?? "";
  return browser.toLowerCase().startsWith("en") ? browser : "en";
}

export const hasTranslation = (key) => key in DICTIONARIES[current] || key in en;

/** Looks up `key` in the current language (falling back to English) and fills {placeholders}. */
export function t(key, params = {}, lang = current) {
  let value = DICTIONARIES[lang]?.[key] ?? en[key] ?? key;
  if (typeof value === "object") {
    const rule = new Intl.PluralRules(lang).select(Number(params.count));
    value = value[rule] ?? value.other;
  }
  return value.replace(/\{(\w+)\}/g, (match, name) => (name in params ? String(params[name]) : match));
}
